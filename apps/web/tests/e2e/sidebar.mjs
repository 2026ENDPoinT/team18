// Real Next shell with synthetic API data; no external providers or writes.
import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const origin = process.env.SIDEBAR_WEB_ORIGIN || 'http://localhost:15110';
const artifacts = process.env.SIDEBAR_ARTIFACTS || '/tmp/team18-sidebar-ui';
mkdirSync(artifacts, { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.P5_BROWSER || '/Applications/Brave Browser.app/Contents/MacOS/Brave Browser', headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 900 } });
const courses = ['프로그래밍 기초', '자료구조', '데이터베이스', '소프트웨어 공학'].map((course_name, i) => ({ course_id: String(i), course_name, recommended_year: i + 1, recommended_term: 1, is_completed: false }));
const writes = [];
await context.addInitScript(() => {
 localStorage.setItem('sb-job-skills-test-auth-token', JSON.stringify({ access_token: 'test.token.value', refresh_token: 'test-refresh', expires_at: Math.floor(Date.now()/1000)+3600, expires_in: 3600, token_type: 'bearer', user: { id: 'sidebar-user', is_anonymous: true } }));
 sessionStorage.setItem('roadmap_request_id', 'sidebar-plan');
 sessionStorage.setItem('roadmap_request_owner', 'sidebar-user');
});
await context.route('**/api/**', route => {
 const request = route.request(), path = new URL(request.url()).pathname;
 if (request.method() !== 'GET') writes.push(path);
 let json;
 if (path.endsWith('/courses')) json = { catalog_id: 'catalog', catalog_version: '1', input_revision: 1, selection_revision: 1, total: courses.length, page: 1, courses, selected_courses: [], selection_summary: { count: 0 }, out_of_scope_completed_courses: [], review_status: 'unconfirmed', reported_missing_courses: false };
 else if (path.endsWith('/roadmap')) json = { status: 'not_started' };
 else if (path.endsWith('/skill-comparison')) json = { job_analysis: { status: 'not_started' } };
 else if (path.endsWith('/activities')) json = { status: 'success', activities: [], sources: [], input_revision: 1, activity_basis: 'goal-only', evaluated_at: new Date().toISOString(), valid_until: new Date(Date.now()+300000).toISOString() };
 else json = { request_id: 'sidebar-plan', input_revision: 1, input: { catalog_id: 'catalog', career_goal: '데이터 분석을 배우고 싶어요.', target_role: '데이터 분석가' } };
 return route.fulfill({ json });
});
const page = await context.newPage(), errors = [];
page.on('pageerror', error => errors.push(error.message));
const toggle = () => page.getByRole('button', { name: /^메뉴 (접기|펼치기)$/ });
const nav = () => page.getByRole('navigation', { name: '주 메뉴', exact: true });
const heading = () => page.locator('.side-toolbar .nav-heading');
const bounds = () => page.evaluate(() => ({ sidebar: document.querySelector('.stepup-side').getBoundingClientRect().width, content: document.querySelector('main').getBoundingClientRect().width, confirmLeft: document.querySelector('.course-confirm-bar')?.getBoundingClientRect().left, overflow: document.documentElement.scrollWidth > innerWidth }));
const screenshot = async name => { await page.addStyleTag({ content: 'nextjs-portal{display:none}' }); await page.screenshot({ path: `${artifacts}/${name}.png` }); };
async function assertToolbar() {
 assert.equal(await heading().innerText(), '역량 체크하기');
 assert.ok(await heading().isVisible());
 const title = await heading().boundingBox(), control = await toggle().boundingBox();
 assert.ok(title.x + title.width <= control.x, 'the toggle sits beside the heading');
 assert.ok(Math.abs(title.y + title.height / 2 - (control.y + control.height / 2)) < 1, 'heading and toggle share a row');
 assert.ok(parseFloat(await heading().evaluate(el => getComputedStyle(el).fontSize)) >= 14);
}
try {
 await page.goto(origin + '/input/courses');
 await page.getByRole('button', { name: '이수 선택 확인', exact: true }).waitFor();
 assert.equal(await toggle().getAttribute('aria-expanded'), 'true');
 await assertToolbar();
 const expanded = await bounds();
 assert.equal(expanded.sidebar, 238); assert.equal(expanded.confirmLeft, 280);
 await screenshot('expanded');
 await page.getByRole('textbox', { name: '과목 검색' }).fill('자료');
 await toggle().focus(); await page.keyboard.press('Enter');
 assert.equal(await toggle().getAttribute('aria-expanded'), 'false');
 assert.equal(await heading().isVisible(), false);
 assert.equal(await toggle().evaluate(el => el === document.activeElement), true);
 const collapsed = await bounds();
 assert.equal(collapsed.sidebar, 72); assert.equal(collapsed.confirmLeft, 114);
 assert.ok(collapsed.content > expanded.content); assert.equal(collapsed.overflow, false);
 assert.equal(await nav().getByRole('link').count(), 5);
 assert.equal(await nav().getByRole('link', { name: '대시보드', exact: true }).count(), 0);
 assert.equal(await nav().getByRole('link', { name: '이수 과목', exact: true }).getAttribute('title'), '이수 과목');
 assert.equal(await page.getByRole('textbox', { name: '과목 검색' }).inputValue(), '자료');
 assert.equal(await page.evaluate(() => localStorage.getItem('stepup-sidebar-collapsed')), 'true');
 await screenshot('collapsed');
 await nav().getByRole('link', { name: '로드맵 결과', exact: true }).click();
 await page.waitForURL('**/result'); await page.locator('.result-overview').waitFor();
 assert.equal(await toggle().getAttribute('aria-expanded'), 'false');
 await page.reload(); await page.locator('.result-overview').waitFor();
 assert.equal(await toggle().getAttribute('aria-expanded'), 'false');
 await nav().getByRole('link', { name: '이수 과목', exact: true }).click();
 await page.locator('.course-confirm-bar').waitFor();
 await page.setViewportSize({ width: 1050, height: 900 });
 assert.equal((await bounds()).confirmLeft, 96);
 await toggle().click();
 assert.equal((await bounds()).sidebar, 210); assert.equal((await bounds()).confirmLeft, 234);
 await assertToolbar();
 await toggle().click();
 await page.setViewportSize({ width: 390, height: 844 });
 assert.equal(await nav().count(), 0);
 assert.equal(await toggle().getAttribute('aria-expanded'), 'false');
 await assertToolbar();
 assert.equal((await bounds()).confirmLeft, await page.locator('.course-year-grid').evaluate(el => el.getBoundingClientRect().left));
 assert.equal((await bounds()).overflow, false);
 await screenshot('mobile-collapsed');
 await toggle().click(); assert.equal(await nav().getByRole('link').count(), 5);
 assert.equal(await toggle().getAttribute('aria-expanded'), 'true');
 await assertToolbar();
 assert.equal((await bounds()).overflow, false);
 await screenshot('mobile-expanded');
 await page.setViewportSize({ width: 320, height: 640 });
 await assertToolbar();
 assert.equal((await bounds()).overflow, false);
 await page.reload(); await page.locator('.course-confirm-bar').waitFor();
 assert.equal(await toggle().getAttribute('aria-expanded'), 'true');
 await page.setViewportSize({ width: 1440, height: 900 });
 assert.equal((await bounds()).sidebar, 238);
 await assertToolbar();
 assert.deepEqual(writes, []); assert.deepEqual(errors, []);
 console.log('PASS: keyboard collapse/expand, icon labels/navigation, state preservation/reload, content and confirmation-bar widths, tablet/mobile resizing, no writes or page errors');
} finally { await context.close(); await browser.close(); }
